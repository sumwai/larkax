#!/usr/bin/env bash
# 门禁自测共用的断言框架。
#
# # 为什么抽出来
#
# 十一个 `check-*.test.sh` 各自抄了同一段十行：`pass` / `fail` 计数、`ok`、
# 把最后一次输出缩进八行打出来的 `bad`、以及结尾那句「通过 N，失败 M」并
# 据此设退出码。逐字相同的拷贝有七份，形状相同的有十一份。
#
# 抄十一遍的代价不是行数，是**改一处要改十一处**：把 `tail -8` 调成 `tail -12`
# 的人只会改他手上那一份，于是同一套自测的失败输出在十一个脚本里长得不一样，
# 而读输出的人得先猜是哪一份的第几条。
#
# 这里只有断言与收尾。**桩件、夹具、每个自测自己的判据一条都不搬**——那些
# 各测各的，合并它们只会把「这一条测的是什么」埋进共享文件里。
#
# # 用法
#
# 自测脚本在设定 `$tmp`（自己的临时目录）之后、第一次调用 `ok` / `bad` 之前：
#
#   . "$(dirname "$0")/gateselftest.sh"    # 或相对本文件的路径
#
# 然后照旧用 `ok`、`bad "<说明>"`，结尾调用 `report`：
#
#   report          # 打印「通过 N，失败 M」，失败数非零时 exit 1
#
# `bad` 会把 **`$last_out` 指向的那个文件**的最后八行缩进打出来。各脚本仍要
# 自己把被测脚本的输出重定向到 `$last_out`——那是它们各自的判据，不是框架的。
#
# 变量名带 `GST_` 前缀，是为了不与各脚本自己的变量撞车：这些文件被 `source`
# 进同一个 shell，一个叫 `fail` 的全局变量会被谁覆盖掉没人说得清。

GST_PASS=0
GST_FAIL=0

# ok：这一条断言通过了。
ok() { GST_PASS=$((GST_PASS + 1)); }

# bad <说明>：这一条断言没通过。
#
# 打印最后一次输出，是为了让看日志的人不必回头翻上下文——自测的价值一半在
# 「哪一条挂了」，另一半在「挂的时候脚本看到了什么」。
bad() {
  echo "✗ $1"
  if [ -n "${last_out:-}" ] && [ -f "$last_out" ]; then
    sed 's/^/    | /' "$last_out" | tail -8
  fi
  GST_FAIL=$((GST_FAIL + 1))
}

# report：打印汇总并据失败数设退出码。
report() {
  echo
  echo "通过 $GST_PASS，失败 $GST_FAIL"
  [ "$GST_FAIL" -eq 0 ] || exit 1
}
