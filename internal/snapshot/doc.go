// Package snapshot 把请求与响应的结构做成骨架：只留形状，不留内容。
//
// 用途只有一个——出问题时能复现。所以每个字段先问一句「复现这个错误需不需要它」：
// 需要就留真实值，不需要就替换为占位描述符。没有第三种情况，
// 不存在「顺手存一下以后可能有用」。
//
// 三条铁律，代码里的每一处判定都从它们推出来：
//
//  1. 白名单放行，默认脱敏。允许表是 allowlist.go 里的数据，表里没有的字段一律
//     替换为占位。上游新增字段时它默认被挡住，直到有人主动把它加进表里。
//     反过来做（黑名单）意味着上游每加一个字段就漏一次，而漏掉的那个是内容。
//  2. 脱敏器出错就丢快照。类型不符、JSON 解析失败、表本身有问题——任何一种情况都
//     返回错误（errors.Is(err, ErrRedaction)），由调用方丢弃整条快照，绝不回落成
//     存原文：宁可失去一次排障能力，不能赌一次泄露。
//  3. 报错信息也是内容。上游的错误正文经常回显用户输入（invalid tool name:
//     <用户的工具名>），所以错误正文整体脱敏，只留 type/code/param 这类枚举字段
//     ——它们不是用户内容，且正好是排障需要的。
//
// 本包是纯函数：不查库、不发 HTTP、不写快照。输入是已经解析好的 JSON 结构
// （map[string]any，见 Decode），输出是骨架与「哪些路径被替换过」的列表。
// Redactor 在构造之后不可变，可以并发使用；工具引用编号属于单次调用的状态，
// 因此不会跨请求串味。
//
// 形状上有一条贯穿全包的规则值得单独说：**放行一个字段，不等于放行上游往这个
// 位置发来的任何取值**。允许表说明的是「我们期望这里放什么」，
// 而落到这一格的东西可能是一次口径变化、一个被别名覆盖的字段，
// 或者客户端自己构造的 JSON。所以除布尔与数字之外，每一个放行档位都自带取值检查，
// 检查不过就按内容处理（只留长度或形状）。allowlist.go 里 allow* 各档的注释
// 写明了每一档检查什么。
//
// 用错方向、传错类型、表坏掉——每一种都返回错误而不是猜。这条链路上
// 每一次「算了，先存着吧」都可能是把原文存下来。
