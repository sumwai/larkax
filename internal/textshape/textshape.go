// Package textshape 校验「写进库、之后会原样打进终端」的文本字段。
//
// 判据只有一条：C0 控制字符（U+0000–U+001F）与 DEL（U+007F）一律拒绝。
// 理由是这些值落库之后会被原样送进终端——清单按「一条记录一行、一个字段
// 一栏」排版，换行会把一栏折出没有栏名的续行、把一条记录拆成两条；ESC
// 这类转义序列还会被终端当成控制指令执行，改标题、改颜色、清屏都能做。
//
// # 为什么拒绝而不是清洗
//
// 清洗会让写入的值与读出的值不是同一个串：回执里打的是原样的输入，库里
// 存的是清洗后的那一份，事后按回执核对时对不上。写入时拒绝，改动发生在
// 命令里，重发一次就能过。
//
// # 收什么、不收什么
//
// 这不是一张字符白名单：空格、标点、中文照收，收窄成「只允许
// `[A-Za-z0-9_-]`」是另一条判据要谈的事。C1（U+0080 起）与零宽字符也
// 不在这一条里——要堵的是折行与转义序列这两类。
package textshape

import (
	"errors"
	"fmt"
)

// ErrControlChar 表示文本里有控制字符（C0 与 DEL）。
//
// 它是一个哨兵，由命令行的 exitCode 归到「参数错」（退出码 2）：错在命令里
// 的那个值，去掉那个字符重发一次就能过，与库里现在有什么无关。各个包把
// 自己的字段名与理由拼在这句话后面，但分类只认这一个值。
var ErrControlChar = errors.New("不能含控制字符")

// whyRendered 是「为什么这个值不能带控制字符」的标准说法。
//
// 收在一处而不是每个调用点各写一句：这些字段被拒的原因是同一个（值会原样
// 进终端），而各写一份时，改了一处、另一处的说法就悄悄旧了。
const whyRendered = "这个值会被原样打进终端的表格或单条回显：" +
	"换行会把一栏拆成两行、把一条记录拆成两条，ESC 这类转义序列还会原样进终端"

// Validate 拒绝 value 里的控制字符。
//
// field 是报错里点名的那个东西，用旗标名（`--name`）或列名都可以——读者要
// 能从这句话里找到该改哪里。没有控制字符时返回 nil，空串同样通过：「没填」
// 与「填了一个坏值」是两件事。
func Validate(field, value string) error {
	for _, r := range value {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("%w：%s里有%s。%s",
				ErrControlChar, field, describe(r), whyRendered)
		}
	}
	return nil
}

// describe 把报错里点名的那个字符说成能照着改的样子：码位，以及那几个
// 在命令行上敲得出来的字符的名字。
//
// 名字不是装饰：`$'a\tb'` 里的那个字符，在报错里写成 U+0009 对不上使用者
// 眼里的东西——他敲的是一个 `\t`。其余 C0 只报码位：它们没有一个人人会
// 随手敲出来的写法。
func describe(r rune) string {
	switch r {
	case '\n':
		return "换行（U+000A）"
	case '\r':
		return "回车（U+000D）"
	case '\t':
		return "制表符（U+0009）"
	case 0x1b:
		return "ESC（U+001B）"
	case 0x00:
		return "NUL（U+0000）"
	case 0x7f:
		return "DEL（U+007F）"
	default:
		return fmt.Sprintf("U+%04X", r)
	}
}
