-- +goose Up
-- 商户分成比例（基点）。
--
-- 一笔消费分给渠道商户的金额 = 售价 × 这个比例，向下取整，零头归平台。
-- 1 bp = 0.01%，10000 就是 100%，例如平台抽 5% 时填 9500。
--
-- # 为什么默认是 0
--
-- 0 表示不分账：消费里没有 merchant_payable 那条分录，账面与这个键
-- 存在之前逐字相同。分成是从平台收入里分出去的钱，默认值不能替部署
-- 决定分多少。
--
-- # 为什么在库里而不是环境变量
--
-- 它不需要在连上数据库之前拿到（见 AGENTS.md 的「配置的分界线」），
-- 而它与定价、分账的其余配置一样，应当跟着数据一起备份与恢复。
--
-- 值不在 0…10000 之内、或者根本读不出来时，结算按 0 处理并写一条告警，
-- 请求照常完成——一个比例写错不该让整条计费路径停摆。
INSERT INTO settings (key, value, description, editable) VALUES
    ('billing.merchant_share_bp', '0',
     '售价里分给渠道商户的比例，单位基点（1 bp = 0.01%，10000 = 100%；平台抽 5% 时填 9500）。分给商户的金额按售价乘以它、向下取整，零头归平台；0 表示不分账。越界或读不出来时按 0 处理并写一条告警，请求照常结算。改完要重启。', true);

-- +goose Down
-- 只删这一行：settings 表本身由 00002 建，回滚到这一版之前它还要用。
DELETE FROM settings WHERE key = 'billing.merchant_share_bp';
