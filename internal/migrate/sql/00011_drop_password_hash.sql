-- +goose Up
-- 删掉 users.password_hash。
--
-- 它是一个**凭证字段**，而全仓（生产代码与测试）既没有写入方也没有读取方：
-- 鉴权只有 API Key 一条路（internal/auth 按 api_keys.key_hash 查，哈希口径
-- 是 SHA-256，见那里的 HashKey），没有口令登录、没有会话、没有 OIDC。
--
-- 一个永远为 NULL 的 password_hash 是在**暗示「这里支持口令登录」**。
-- 下一个照 schema 写代码的人会先假设那条通道存在，再去发现它不存在——
-- 这与「文档与实现不一致本身就是缺陷」是同一类。
--
-- 控制台登录若真要做，OIDC / 一次性令牌 / API Key 都可以，而这一列的
-- 存在并不让那条路更好走：它只有一个裸的 text，没有任何配套（口令强度、
-- 失败锁定、重置流程、会话表），照它实现等于从零开始。
--
-- 所以删掉，代价只是「将来多一条迁移」——下面那段 Down 就是加回来的写法。
--
-- 删于本迁移（00011）；要加回来照下面 Down 段写，或直接 `goose down`。
--
-- 与 00010（删 reconciliation_runs）的区别：那一次删的是**被更想清楚的一版
-- 设计取代**的表；这一次删的是一个从未开工的能力留下的占位。
ALTER TABLE users DROP COLUMN password_hash;

-- +goose Down
-- 按 00001 的原样加回来：可空、无默认值，所以不影响任何现有行。
--
-- 注意回滚后的状态是「列在那儿，而仍然没有写入方」——恢复的是列的**存在**，
-- 不是那条从未存在的口令通道。要真的做口令登录，先定配套的那几件事。
ALTER TABLE users ADD COLUMN password_hash text;
