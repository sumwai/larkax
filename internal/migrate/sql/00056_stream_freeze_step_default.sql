-- +goose Up
-- 流式递进冻结的默认阈值段：4096 → 1024。
--
-- # 为什么改
--
-- 4096 是按「几乎覆盖所有输出」选的：实测输出侧的 p95 是 3,990，4096 落在
-- p95 与 p99 之间。但第一段要盖住的是**多数**请求，不是几乎全部——实测
-- 85,909 条流式调用的输出侧 p75 是 976 个 token，1024 是盖住它的最小 2 的幂，
-- 而 roundUpTo(produced, step) 按 2 的幂整除时没有奇怪的对齐。
--
-- 代价的方向没变（见 00028 的注释）：调小它，数据库往返与同一用户行锁的持锁
-- 次数变多，冻住的余量变少。这个值按「多数请求在第一段就冻够」定——它盯的是
-- 输出侧分布，不是某一种部署形态的往返成本。
--
-- # 只改仍停在旧默认值的行
--
-- 运维手工调过这个值的，有它自己的理由（例如按自己的输出分布重新算过）；
-- 迁移不该把那次调整抹掉。
UPDATE settings
   SET value = '1024', updated_at = now()
 WHERE key = 'billing.stream_freeze_step'
   AND value = '4096';

-- +goose Down
-- 回到 4096，同样只动仍停在 1024 的行。
--
-- 这**不还原**人工设置：手工把值改成 1024 的那一行，与迁移写下的那一行在库里
-- 长得一样，回滚分不出来，会一起被改回 4096。要保住就先把当前值记下来。
UPDATE settings
   SET value = '4096', updated_at = now()
 WHERE key = 'billing.stream_freeze_step'
   AND value = '1024';
