-- +goose Up
-- model_catalog 加一列：这个模型在上游哪几条端点上被服务。
--
-- # 为什么这一列属于模型，而不属于渠道
--
-- 一个上游同时有 /v1/chat/completions、/v1/responses、/v1/messages 三套端点，
-- 走哪一套**由模型决定**：同一个账号下 A 模型只在 chat 那边被服务、B 模型只在
-- responses 那边。往模型不支持的那条端点发，上游回 400 unsupported_model——
-- 从我们这边看与「模型不存在」长得一样，而且只有真打一次才发现。
--
-- 渠道的 type 说的是**协议**（它决定用哪个适配器、那条适配器往哪条路径发），
-- 不是「这条渠道只服务哪个端点」。判据的两侧要对上才放行：一侧是渠道那条
-- 适配器实际打的路径（channel.Protocol.Endpoint），另一侧是这一列。
--
-- # 三种状态（与 00025 那六个能力列同一套口径）
--
--   NULL  未知：这一项从没配过，**不参与**任何判据
--   {}    明确声明：一条端点都不支持
--   非空  支持这几条
--
-- 「未知」必须与「一条都不支持」分开：前者放行、后者让这条候选出局。把 NULL
-- 读成空数组会让一条只填了名字的记录选不到任何渠道，而那个上游其实服务着
-- 这个模型——那正是 00025 修过的同一类缺陷。
--
-- # 存量一行都不动
--
-- 这一列可空、没有默认值，所以这条迁移只有一句 DDL：**一条 UPDATE 都没有**。
-- 既有行全是 NULL = 未知 = 不判，行为与迁移之前完全一致；要按端点选路，由
-- 运维显式地给模型配上端点。
--
-- # 这一列会过时
--
-- 上游开一条新端点、或者把某个模型挪到别的端点上，库里不会自己变。这一版
-- 没有任何自动采集会刷新它，由人工经目录管理接口维护（`larkaxctl model` 的
-- 创建/修改里的 endpoints 那一组字段）。所以它记的是「我们**知道**的声明」，
-- 不是「上游此刻的事实」——判出「这个模型不在这条端点上」时，先怀疑这一列
-- 是不是旧的。
ALTER TABLE model_catalog ADD COLUMN supported_endpoints text[];

-- 在 psql 里看这一列的人要能立刻分清 NULL 与 `{}`，而不是去翻代码。
-- 取值是适配器实际打的路径（见 channel.Endpoint），与上游模型清单里那份
-- supported_endpoints 是同一套口径。
COMMENT ON COLUMN model_catalog.supported_endpoints IS
    'NULL = 未知（没配过，不参与选路判据）；{} = 明确一条都不支持；非空 = 支持这几条。取值见 channel.Endpoint。这一列人工维护、会过时，见 00027。';

-- +goose Down
-- 直接丢列：这一列的内容没有任何别的地方放得下。
--
-- 回滚意味着同时退回旧版本的二进制，而旧代码根本不读这一列；丢的是「这个
-- 模型在哪几条端点上被服务」这一条声明，不回填、也不猜测。
ALTER TABLE model_catalog DROP COLUMN supported_endpoints;
