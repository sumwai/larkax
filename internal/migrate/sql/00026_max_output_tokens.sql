-- +goose Up
-- 单次输出上限：调用方在请求体里声明的 max_tokens 的上界。
--
-- # 为什么需要它
--
-- 预留的输出侧按调用方给的 max_tokens 算（见 internal/billing 的 Reserve），
-- 而这个字段原先只有「必须为正」这一条校验。于是「把 max_tokens 当上限而不是
-- 预期来填」的调用方（不少 SDK 的默认值就很大）单发一条就会被按那个上界冻住
-- 余额：余额 $10 的账户发一条 max_tokens=100K 的请求，第一条就被「可用余额
-- 不足」拒掉——而拒绝的理由与真实原因不是同一件事。填到乘法放不下时更坏：
-- 那会以「算不出预留上界」报出来，把一个字段填得离谱说成了我们的内部故障。
--
-- 所以非流式请求超过这条上界时**拒绝**，并当场给出允许的上限。流式不在这条
-- 上界里：它有中途观测点，钱的处置是随流递进冻结。
--
-- # 这一行是全局默认值
--
-- 按模型判的那个数取模型目录（model_catalog.output_limit）——那一列本来就是
-- 逐模型的，而把同一个数在 settings 里再抄一份，两份迟早不一致（见
-- internal/settings 的包注释）。这一行只在目录里没登记时兜底。
--
-- # 为什么在库里而不是环境变量
--
-- 它不需要在连上数据库之前拿到（见 AGENTS.md 的「配置的分界线」）。
--
-- # 默认值 65536 是怎么来的
--
-- 取「目前已知的最大单次输出」这个量级：64K 覆盖了 Claude 各档模型声明的
-- 输出上限，而它是一道**我们愿意单次承担多少**的界，不是上游的能力。调大它
-- 要同时想清楚一次请求能冻住多少余额；调小它会拒掉本来合法的长输出请求。
INSERT INTO settings (key, value, description, editable) VALUES
    ('billing.max_output_tokens', '65536',
     '单次请求允许声明的 max_tokens 上界。模型目录里登记了 output_limit 的按目录那个数判，没登记的按这个数判；非流式请求超过它会被拒（400）。', true);

-- +goose Down
-- 只删这一行：settings 表本身由 00002 建，回滚到这一版之前它还要用。
DELETE FROM settings WHERE key = 'billing.max_output_tokens';
