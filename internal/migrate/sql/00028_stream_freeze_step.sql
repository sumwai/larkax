-- +goose Up
-- 流式递进冻结的阈值段（token）。
--
-- # 它同时是两个量
--
-- 流式请求不再按调用方声明的 max_tokens 一次性冻满，而是边转发边按本地累计的
-- 真实产出补冻（见 internal/gateway 的 streamFreeze 与 #498）。这个数说的是**每
-- 产出多少 token 补冻一次**，而它同时就是「最多领先已产出量多少」——调大它，
-- 数据库往返次数少、冻住的余量多；调小反之。
--
-- 之所以是一个数而不是两个：两者由同一个机制产生（补冻的检查点就是段边界），
-- 拆成两个旋钮之后它们迟早会被配成互相矛盾的一对，而那种配置不会报错——它
-- 只是让「多久检查一次」与「冻住多少」不再对得上。
--
-- # 为什么在库里而不是环境变量
--
-- 它不需要在连上数据库之前拿到（见 AGENTS.md 的「配置的分界线」）。
--
-- # 默认值 4096 是怎么来的
--
-- 取「一次检查的成本」与「一次检查之间能产出多少」的折中：4K token 的输出
-- 在常见模型上要好几秒才产得出来，而一次补冻只是一次两三条语句的事务。
-- 调小它会把数据库往返摊到每几百个 token 一次；调大它会按这个数多冻余额，
-- 而多冻的那部分正是这一条要解决的问题的另一面。
INSERT INTO settings (key, value, description, editable) VALUES
    ('billing.stream_freeze_step', '4096',
     '流式请求递进冻结的阈值段（token）：本地累计产出每越过一个段就补冻一次，同时这也是冻结额最多领先已产出量的量。调大它，数据库往返少、冻住的余量多；调小反之。', true);

-- +goose Down
-- 只删这一行：settings 表本身由 00002 建，回滚到这一版之前它还要用。
