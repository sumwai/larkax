-- +goose Up
-- 余量见底的渠道重新进入候选集的冷却期（秒）。
--
-- # 它补的是哪条死路
--
-- 额度探测是「用到时才发生」的：渠道被路由真正尝试之前，探测才可能发起。
-- 而余量见底的渠道会被读侧排除出候选集，于是没有请求会命中它，探测也就
-- 不会再触发——上游的额度后来恢复了，我们永远发现不了，渠道一直停着。
--
-- 这个键是那条路径的出口：距上一次**尝试**探测已满这个时长时，读侧放行
-- 一次，让渠道回到候选集里试一次；真被尝试到时探测会再问一次上游。
-- 仍然是 0 的话，那次尝试会把 last_probe_attempt_at 推到当下，它就要再等
-- 一个冷却期。没有后台轮询：放行仍然由请求驱动。
--
-- # 为什么默认 900 秒
--
-- 与连续失败那条冷却期（internal/channels 的 streakCooldown）取同一个数。
-- 它对见底渠道的打扰上限是「一个冷却期一次注定失败的尝试」，而一个已经
-- 恢复的渠道最多晚这么久重新可用。取更短会让一个额度硬上限的上游被更频繁
-- 地试探，取更长会让恢复慢一拍。它比默认探测间隔（300 秒）长，于是冷却期
-- 到点时探测通常也已经到期。
--
-- # 它与探测间隔的关系
--
-- 这个值只决定渠道多快回到候选集；真正再问一次上游仍由
-- quota.probe_interval_seconds 把关。配得比探测间隔还短时，渠道会先被放行、
-- 但要等探测门槛到了才会被重新探测。
INSERT INTO settings (key, value, description, editable) VALUES
    ('quota.exhausted_cooldown_seconds', '900',
     '余量见底的渠道重新进入候选集的冷却期（秒）：距上次探测尝试满这个时长就放行一次，被尝试到时重新探测；仍有 0 就再等一个冷却期。它只决定多快回到候选集，真正再探测仍由 quota.probe_interval_seconds 把关。零值与负数不合法，越界时服务拒绝启动。', true);

-- +goose Down
-- 只删这一行：settings 表本身由 00002 建，回滚到这一版之前它还要用。
DELETE FROM settings WHERE key = 'quota.exhausted_cooldown_seconds';
