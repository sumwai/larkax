// Package expr 求值计价规则的表达式。
//
// 一条计价规则是一段表达式源码（数据库 pricing_rules.expr），求值之后得到的是
// **一组单价**（billing.Prices）与**一次性费用**（billing.Charges），不是金额。
//
// 为什么返回单价而不是金额：单价乘用量那一步由 billing.ComputeWithCharges 做，
// 而它是整数定点运算、没有舍入、并且逐项拆得开。把乘法留在这一侧意味着
// 对账时能回答「这一分钱是哪个环节产生的」；把乘法搬进表达式则每次都要在
// 浮点里做一遍定点估算，误差会散进每一行明细里。
//
// # 用量只作条件，不作乘数
//
// 规则作者写 `len <= 32000 ? {...} : {...}`，不写 `p * 2.5`。原因是预留：
// 预留要在请求发出前算出一个上界，而「单价 × 用量」的上界需要知道用量上界，
// 那要求规则里每一个用量乘数都单调可界。条件式不一样——把每个条件的所有分支
// 都取一遍最高价，就得到一个与用量无关的上界（见 Program.EvalWorstCase）。
// 这条约定由 Compile 强制：用量变量出现在乘数位置会编译失败。
//
// # 时间从 Env 传进来
//
// 求值绝不读墙钟。预留与结算必须给出同一个答案，而读 time.Now() 会让
// 跨整点的请求按低谷预留、按高峰结算，撞上 Capped——而 Capped 本该是
// 「上界算错了」的信号，不该成为常态。事后复算同理：没有求值时刻就无法重放。
//
// # 这是商家可写的输入
//
// 规则源码由商家填写，因此本包按不可信输入处理它：源码长度、AST 节点数、
// 嵌套深度都有上限；除数学函数外的内置函数一律禁用（含 now/date/duration/
// toJSON/fromJSON/toBase64/fromBase64，以及 math 包那些浮点边界不明确的函数）；
// 结果必须是数值，NaN/Inf 与负数在转成 money.Amount 之前就被拦下。
