// Package cli 是 larkaxctl 的框架层：退出码分类、输出格式与样式、表格对齐、
// 旗标注册、全局选项、逐条命令的共用助手。
//
// # 它为什么在 internal/ 下
//
// 唯一的调用方是 cmd/larkaxctl（package main）。命令那一层（各条命令本身、
// 分派表、帮助文案常量）还在 main 里，通过导出名调用这一层；这一层反过来
// 不引用 main 的任何东西，所以不构成环。
//
// # 一处分层边界：帮助文案不在这一层
//
// 用户看到的帮助文本是 main 里那几十个手写的 *Usage 常量，它们是**唯一来源**。
// 这一层只负责把它打出去（PrintUsage）与给它上色（Palette.PaintHelp），
// 不持有任何一句文案。改帮助去改那些常量，别往这里加。
//
// # 收集会话
//
// 生成补全时要把每条命令路径按 `<路径> -h` 走一遍，抢在解析阶段之前把各命令
// 注册的选项记下来。那期间有五个地方要让路（不连库、不摘位置参数——两处、
// 不短路帮助、才记账），它们统一问 CollectingFlags；置位与复位只在
// CollectFlags 一处。见 collect.go。
